"""Generate `ZesuExec/Fn/DTF/LeavesGen.lean`: one `leaf_gen` instance per DTF leaf that passes.

Run from `exec-spike/` after `lake build ZesuExec.Fn.DTF.Gen`:

    python3 OPEN/DTF/gen_leaves.py

A leaf gets an instance when its source is not the entry, `SrcOk` and `GenCheck` evaluate to
`true` (`#eval` over the cut table, the same functions the instances check by `decide`), its
source's cut lemma `DTF.cut_<pc>` is proved in `Leaves.lean`, and no hand-written file
(every other file of `ZesuExec/Fn/DTF/`) proves it.
"""
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'ZesuExec/Fn/DTF/LeavesGen.lean'
LEAVES = ROOT / 'ZesuExec/Fn/DTF/Leaves.lean'
HAND = sorted(p for p in (ROOT / 'ZesuExec/Fn/DTF').glob('*.lean') if p != OUT)

PROBE = '''import ZesuExec.Fn.DTF.Gen
open ZesuExec ZesuExec.Sym ZesuExec.Fn.DTF
#eval show IO Unit from do
  let mut i := 0
  for d in table do
    let ls := leavesAt d.pc
    let mut j := 0
    for l in ls do
      if d.pc != entry && SrcOk d && GenCheck d l then
        IO.println s!"PASS {i} {d.pc} {j}"
      j := j + 1
    i := i + 1
'''

HEAD = '''import ZesuExec.Fn.DTF.Leaves
import ZesuExec.Fn.DTF.Gen

/-!
# DTF leaves closed by `leaf_gen` (programme plan S7 step 4), in table order

Each instance checks by `decide` `GenCheck` (the leaf ends at a plain cut or calls `decodeItem`
with a return site, its only obligations are reads at the source's byte-loop cursor, it writes
only frame words below the save area, and it carries the target's shape, arms, `rest` — kept, or
advanced by the source's `decodeItem` outcome —, cursor and budget over from the source) and
`SrcOk` (the source's facts follow from its assertion), and takes the source's cut lemma.
Generated by `OPEN/DTF/gen_leaves.py`: one instance per leaf for which `GenCheck` evaluates to
`true`.
-/

namespace ZesuExec.Fn.DTF
open ZesuExec ZesuExec.Sym ZesuExec.Machine ZesuExec.Vc

set_option maxRecDepth 20000

'''


def main() -> None:
    with tempfile.NamedTemporaryFile('w', suffix='.lean', delete=False) as f:
        f.write(PROBE)
        probe = f.name
    res = subprocess.run(['lake', 'env', 'lean', probe], cwd=ROOT, capture_output=True,
                         text=True)
    pathlib.Path(probe).unlink()
    if res.returncode != 0:
        sys.exit(res.stdout + res.stderr)
    cuts = set(re.findall(r'theorem DTF\.cut_([0-9a-f]+)', LEAVES.read_text()))
    hand = set()
    for p in HAND:
        hand |= set(re.findall(r'theorem DTF\.leaf_([0-9a-f]+_\d+)', p.read_text()))
    rows = []
    for line in res.stdout.splitlines():
        m = re.match(r'PASS (\d+) (\d+) (\d+)$', line)
        if m:
            i, pc, j = int(m.group(1)), int(m.group(2)), int(m.group(3))
            if f'{pc:08x}' in cuts and f'{pc:08x}_{j}' not in hand:
                rows.append((i, pc, j))
    body = []
    for i, pc, j in rows:
        h = f'{pc:08x}'
        body.append(
            f'theorem DTF.leaf_{h}_{j} : LeafGoal DTF.plan DTF.plan.cuts[{i}]! '
            f'((DTF.plan.leaves 0x{h})[{j}]!) :=\n'
            f'  leaf_gen (table[{i}]!) ((leavesAt 0x{h})[{j}]!) (by decide) DTF.cut_{h} '
            f'(by decide) (by decide)\n')
    OUT.write_text(HEAD + ''.join(body) + '\nend ZesuExec.Fn.DTF\n')
    print(f'{len(rows)} instances -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
