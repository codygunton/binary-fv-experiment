#!/usr/bin/env python3
"""Render Unicorn snapshots of `alt_fl_alloc.alloc` / `free` (`tools/snap.py --fn Alloc|Free`,
schema `zesu-snap/1`) as Lean data for their `post_snapshot` theorems (contract rule (b)).

    snap_alloc.py --fn Alloc --ns ZesuExec.Fn.Alloc.AllocF --snaps test/snapshots/Alloc \
        --inputs tools/snap_inputs/alloc.json --out ZesuExec/Fn/Alloc/SnapsAlloc.lean

Per snapshot: the registers at entry and exit, the exit `pc`, the address of every changed byte,
the live blocks of the input row, and, at entry and at exit, the words `Alloc.decodeB` reads: the
22 head cells, `HEAP_POS`, `HEAP_TOP` and the first word of every block on a chain (followed here
only to list the words; the Lean side follows the chains itself and fails on a missing word).
"""
import argparse
import json
from pathlib import Path

FL_BASE, POS_ADDR, TOP_ADDR = 0xa0534008, 0xa0d34520, 0xa0d34528


def byte_map(rows):
    out = {}
    for r in rows:
        for i, b in enumerate(bytes.fromhex(r['hex'])):
            out[r['base'] + i] = b
    return out


def words(mem):
    """`(address, word)` for every word `decodeB` reads that the snapshot holds."""
    out = {}

    def take(a):
        if a not in out and all(a + j in mem for j in range(8)):
            out[a] = int.from_bytes(bytes(mem[a + j] for j in range(8)), 'little')
        return out.get(a)

    take(POS_ADDR)
    take(TOP_ADDR)
    for k in range(22):
        p, n = take(FL_BASE + 8 * k), 0
        while p and n < 64:
            p, n = take(p), n + 1
    return sorted(out.items())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fn', required=True, choices=['Alloc', 'Free'])
    ap.add_argument('--ns', required=True)
    ap.add_argument('--snaps', type=Path, required=True)
    ap.add_argument('--inputs', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args()
    rows = {r['id']: r for r in json.loads(a.inputs.read_text())['inputs']}
    lst = lambda xs: '[' + ', '.join(str(x) for x in xs) + ']'  # noqa: E731
    pairs = lambda xs: '[' + ', '.join(f'({x}, {y})' for x, y in xs) + ']'  # noqa: E731
    with open(a.out, 'w') as o:
        o.write(f'-- Generated by tools/snap_alloc.py from {a.snaps}. Do not edit.\n')
        o.write('import ZesuExec.Fn.Alloc.Snap\n\n')
        o.write(f'namespace {a.ns}\nopen ZesuExec.Fn.Alloc\n\n')
        names = []
        for j, f in enumerate(sorted(a.snaps.glob('*.json'))):
            s = json.loads(f.read_text())
            assert s['fn'] == a.fn and s['stop'] == 'returned', f
            ent, ext = s['entry'], s['exit']
            mem0 = byte_map(ent['mem'])
            chg = byte_map(ext['changed'])
            mem1 = {**mem0, **chg}
            live = [tuple(b) for b in rows[s['input']].get('live', [])]
            names.append(f'snap{j}')
            o.write(f'/-- Snapshot `{s["input"]}`. -/\n'
                    f'def snap{j} : Snap :=\n  {{ regs0 := {lst(ent["regs"])},\n'
                    f'    regs1 := {lst(ext["regs"])},\n    pc1 := {ext["pc"]},\n'
                    f'    mem0 := {pairs(words(mem0))},\n    mem1 := {pairs(words(mem1))},\n'
                    f'    changed := {lst(sorted(chg))},\n    live := {pairs(live)} }}\n\n')
        o.write(f'/-- The Unicorn snapshots (`{a.snaps}`), as `Snap` values. -/\n')
        o.write('def snaps : List Snap := [' + ', '.join(names) + ']\n\n')
        o.write(f'end {a.ns}\n')


if __name__ == '__main__':
    main()
