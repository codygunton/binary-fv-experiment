#!/usr/bin/env python3
"""Render Unicorn snapshots (`tools/snap.py`, schema `zesu-snap/1`) of slice functions as Lean data
for the `post_snapshot` theorems (programme plan, contract rule (b)).

    snap_post.py --fn R8330 --ns ZesuExec.Fn.Rotate.C8330 --elem 48 \
        --snaps test/snapshots/R8330 --out ZesuExec/Fn/Rotate/C8330/Snaps.lean

Per snapshot: the argument registers, `sp` and `ra` at entry, the exit `pc` and registers, the
slice bytes (`a1 * elem` bytes at `a0`) at entry and at exit, and the address of every byte that
changed. The Lean side (`Rotate.SnapOk`) checks `Post` on exactly these values.
"""
import argparse
import json
from pathlib import Path


def byte_map(rows):
    out = {}
    for r in rows:
        bs = bytes.fromhex(r['hex'])
        for i, b in enumerate(bs):
            out[r['base'] + i] = b
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fn', required=True)
    ap.add_argument('--ns', required=True)
    ap.add_argument('--elem', type=int, required=True)
    ap.add_argument('--snaps', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args()
    items = []
    for f in sorted(a.snaps.glob('*.json')):
        s = json.loads(f.read_text())
        assert s['fn'] == a.fn and s['stop'] == 'returned', f
        ent, ext = s['entry'], s['exit']
        mem0 = byte_map(ent['mem'])
        chg = byte_map(ext['changed'])
        mem1 = {**mem0, **chg}
        regs0, regs1 = ent['regs'], ext['regs']
        p, n = regs0[9], regs0[10]
        size = n * a.elem
        before = [mem0[p + j] for j in range(size)]
        after = [mem1[p + j] for j in range(size)]
        items.append((s['input'], regs0, regs1, ext['pc'], before, after, sorted(chg)))
    lst = lambda xs: '[' + ', '.join(str(x) for x in xs) + ']'  # noqa: E731
    with open(a.out, 'w') as o:
        o.write(f'-- Generated by tools/snap_post.py from {a.snaps}. Do not edit.\n')
        o.write('import ZesuExec.Fn.Rotate.Snap\n\n')
        o.write(f'namespace {a.ns}\nopen ZesuExec.Fn.Rotate\n\n')
        o.write('/-- The Unicorn snapshots (`test/snapshots`), as `Snap` values. -/\n')
        o.write('def snaps : List Snap := [\n')
        o.write(',\n'.join(
            f'  -- {i}\n  {{ regs0 := {lst(r0)},\n    regs1 := {lst(r1)},\n    pc1 := {pc},\n'
            f'    before := {lst(b)},\n    after := {lst(af)},\n    changed := {lst(c)} }}'
            for i, r0, r1, pc, b, af, c in items))
        o.write(']\n\n')
        o.write(f'end {a.ns}\n')


if __name__ == '__main__':
    main()
