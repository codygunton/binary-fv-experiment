#!/usr/bin/env python3
"""Render Unicorn snapshots (`tools/snap.py`, schema `zesu-snap/1`) of slice functions as Lean data
for the `post_snapshot` theorems (programme plan, contract rule (b)).

    snap_post.py --fn R8330 --ns ZesuExec.Fn.Rotate.C8330 --elem 48 \
        --snaps test/snapshots/R8330 --out ZesuExec/Fn/Rotate/C8330/Snaps.lean
    snap_post.py --kind merge --fn M7964 --ns ZesuExec.Fn.MergeInPlace.C7964 \
        --snaps test/snapshots/M7964 --out ZesuExec/Fn/MergeInPlace/C7964/Snaps.lean
    snap_post.py --kind keyed --fn M11564 --ns ZesuExec.Fn.MergeInPlace.C11564 \
        --snaps test/snapshots/M11564 --out ZesuExec/Fn/MergeInPlace/C11564/Snaps.lean

Rotate (default): per snapshot the argument registers, `sp` and `ra` at entry, the exit `pc` and
registers, the slice bytes (`a1 * elem` bytes at `a0`) at entry and at exit, and the address of
every byte that changed. The Lean side (`Rotate.SnapOk`) checks `Post` on exactly these values.

Merge (`mergeInPlace(items, &A, &B)`, 32-byte elements): the same registers, `pc` and changed
addresses, the ranges `A`, `B` (the `u64` pairs at `a1`, `a2` in the entry memory) and the items
bytes `[0, 32 * B.end)` at `a0` at entry and at exit; checked by `MergeInPlace.SnapOk`.

Keyed (merge whose elements start with a byte slice `{ptr, len}`, ordered by the pointed-to
bytes): as merge, plus `keys`, the `(ptr, len, bytes)` of every distinct slice among the entry
elements `[0, B.end)`, its bytes read from the entry memory.
"""
import argparse
import json
from pathlib import Path


def byte_map(rows):
    out = {}
    for r in rows:
        bs = bytes.fromhex(r['hex'])
        for i, b in enumerate(bs):
            out[r['base'] + i] = b
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fn', required=True)
    ap.add_argument('--ns', required=True)
    ap.add_argument('--kind', choices=['rotate', 'merge', 'keyed'], default='rotate')
    ap.add_argument('--elem', type=int, help='element size (rotate; merge elements are 32 bytes)')
    ap.add_argument('--snaps', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args()
    if a.kind == 'rotate' and a.elem is None:
        ap.error('--elem is required for --kind rotate')
    u64 = lambda mem, x: int.from_bytes(bytes(mem[x + j] for j in range(8)), 'little')  # noqa: E731
    items = []
    for f in sorted(a.snaps.glob('*.json')):
        s = json.loads(f.read_text())
        assert s['fn'] == a.fn and s['stop'] == 'returned', f
        ent, ext = s['entry'], s['exit']
        mem0 = byte_map(ent['mem'])
        chg = byte_map(ext['changed'])
        mem1 = {**mem0, **chg}
        regs0, regs1 = ent['regs'], ext['regs']
        if a.kind in ('merge', 'keyed'):
            p = regs0[9]
            rng = (u64(mem0, regs0[10]), u64(mem0, regs0[10] + 8),
                   u64(mem0, regs0[11]), u64(mem0, regs0[11] + 8))
            size = 32 * rng[3]
        else:
            p, n = regs0[9], regs0[10]
            rng, size = None, n * a.elem
        before = [mem0[p + j] for j in range(size)]
        after = [mem1[p + j] for j in range(size)]
        keys = None
        if a.kind == 'keyed':
            sl = sorted({(u64(mem0, p + 32 * e), u64(mem0, p + 32 * e + 8)) for e in range(rng[3])})
            keys = [(q, n, [mem0[q + j] for j in range(n)]) for q, n in sl]
        items.append((s['input'], regs0, regs1, ext['pc'], rng, before, after, sorted(chg), keys))
    lst = lambda xs: '[' + ', '.join(str(x) for x in xs) + ']'  # noqa: E731
    mod = 'Rotate' if a.kind == 'rotate' else 'MergeInPlace'
    with open(a.out, 'w') as o:
        o.write(f'-- Generated by tools/snap_post.py from {a.snaps}. Do not edit.\n')
        o.write(f'import ZesuExec.Fn.{mod}.Snap\n\n')
        o.write(f'namespace {a.ns}\nopen ZesuExec.Fn.{mod}\n\n')
        for j, (i, r0, r1, pc, rng, b, af, c, ks) in enumerate(items):
            ranges = ('' if rng is None else
                      f'    aS := {rng[0]},\n    aE := {rng[1]},\n    bS := {rng[2]},\n    bE := {rng[3]},\n')
            # a literal of several hundred elements exceeds Lean's default elaboration depth
            o.write(f'set_option maxRecDepth 8000 in\n/-- Snapshot `{i}`. -/\n'
                    f'def snap{j} : Snap :=\n  {{ regs0 := {lst(r0)},\n    regs1 := {lst(r1)},\n'
                    f'    pc1 := {pc},\n{ranges}    before := {lst(b)},\n    after := {lst(af)},\n'
                    f'    changed := {lst(c)}')
            if ks is not None:
                o.write(',\n    keys := [' + ', '.join(f'({q}, {n}, {lst(bs)})' for q, n, bs in ks) + ']')
            o.write(' }\n\n')
        o.write('/-- The Unicorn snapshots (`test/snapshots`), as `Snap` values. -/\n')
        o.write('def snaps : List Snap := [' + ', '.join(f'snap{j}' for j in range(len(items))))
        o.write(']\n\n')
        o.write(f'end {a.ns}\n')


if __name__ == '__main__':
    main()
