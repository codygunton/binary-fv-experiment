"""Cost model from the ledger and the merged map (programme plan S8).

`render(map, rows)` returns the Markdown of `map/COSTMODEL.md`:

1. per item kind: count, median and total minutes and dollars (ledger rows by `kind`), with leaf
   counts by state from the map, and manual leaves by residual class;
2. per function with proof material or ledger rows: the static feature vector (cut points, loops,
   call sites, joins, `leaves_estimate`, instructions) beside its actual totals;
3. the share of leaves closed automatically before and after each automation item, read from
   ledger notes `auto_share <fn> <auto>/<total> -> <auto>/<total>`, and the share now;
4. for the target set, function counts and feature sums by state.

Rates and counts only: no extrapolated total.
"""
import re
import statistics

FEATURES = ('cuts', 'loops', 'calls', 'joins', 'leaves_estimate', 'n_instr')
SHARE_RE = re.compile(r'auto_share\s+(\S+)\s+(\d+)/(\d+)\s*->\s*(\d+)/(\d+)')


def features(f):
    """The static feature vector of a map function."""
    return {'cuts': len(f.get('cuts') or []), 'loops': len(f.get('loops') or []),
            'calls': len(f.get('calls') or []), 'joins': len(f.get('joins') or []),
            'leaves_estimate': f.get('leaves_estimate') or 0, 'n_instr': f.get('n_instr') or 0}


def residual_class(residual):
    """A manual leaf's residual class: the head symbol recorded by `zesu_auto`, or `none`."""
    if not residual:
        return 'none'
    m = re.search(r'head ([^\s;]+)', residual)
    return m.group(1) if m else residual.split(';')[0].strip()


def _num(x):
    return x if isinstance(x, (int, float)) else 0


def _fmt(x):
    if x is None:
        return '-'
    if isinstance(x, float):
        return f'{x:.1f}' if x != int(x) else str(int(x))
    return str(x)


def is_share_note(r):
    """A zero-minute row that only records an auto-closed share (not effort)."""
    return not _num(r.get('minutes')) and bool(SHARE_RE.search(r.get('note') or ''))


def kind_table(rows):
    """{kind: (count, median minutes, total minutes, median usd, total usd)}; share-note rows
    are not effort and are left out."""
    rows = [r for r in rows if not is_share_note(r)]
    out = {}
    for kind in sorted({r.get('kind') for r in rows if r.get('kind')}):
        rs = [r for r in rows if r.get('kind') == kind]
        mins = [_num(r.get('minutes')) for r in rs]
        usd = [_num(r.get('usd')) for r in rs]
        out[kind] = (len(rs), statistics.median(mins), sum(mins), statistics.median(usd), sum(usd))
    return out


def leaves_by_state(m):
    """Counts of plan leaves by state, and manual leaves by residual class."""
    states = {'auto': 0, 'manual': 0, 'open': 0}
    classes = {}
    for f in m.get('functions', []):
        for c in f.get('vc_cuts') or []:
            for lf in c.get('leaves') or []:
                st = lf.get('state')
                if st in states:
                    states[st] += 1
                if st in ('manual', 'open'):
                    k = residual_class(lf.get('residual'))
                    classes[k] = classes.get(k, 0) + 1
    return states, classes


def share_history(rows):
    """(ts, item, fn, before auto, before total, after auto, after total) from ledger notes."""
    out = []
    for r in rows:
        mt = SHARE_RE.search(r.get('note') or '')
        if mt:
            fn, a0, t0, a1, t1 = mt.groups()
            out.append((r.get('ts'), r.get('item'), fn, int(a0), int(t0), int(a1), int(t1)))
    return sorted(out, key=lambda x: x[0] or '')


def _pct(a, t):
    return f'{100 * a / t:.0f}%' if t else '-'


def render(m, rows):
    lines = ['# Cost model (programme plan S8)', '',
             'Generated by `python3 -m zmap costmodel` from `map/map.json` and `map/ledger.jsonl`.',
             'Rates and counts only; no extrapolated total.', '']

    lines += ['## Effort by item kind', '',
              '| kind | items | median min | total min | median $ | total $ |',
              '|---|---:|---:|---:|---:|---:|']
    for kind, (n, mmed, mtot, umed, utot) in kind_table(rows).items():
        lines.append(f'| {kind} | {n} | {_fmt(mmed)} | {_fmt(mtot)} | {_fmt(umed)} | {_fmt(utot)} |')
    states, classes = leaves_by_state(m)
    total_leaves = sum(states.values())
    leaf_rows = [r for r in rows if r.get('kind') == 'leaf']
    leaf_min = sum(_num(r.get('minutes')) for r in leaf_rows)
    lines += ['', f'Plan leaves: auto {states["auto"]}, manual {states["manual"]}, '
              f'open {states["open"]} (auto share {_pct(states["auto"], total_leaves)}). '
              f'Ledger `leaf` minutes per manual leaf: '
              f'{_fmt(leaf_min / states["manual"]) if states["manual"] else "-"}.', '',
              '| residual class (manual and open leaves) | leaves |', '|---|---:|']
    for k, n in sorted(classes.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f'| {k} | {n} |')

    lines += ['', '## Functions: static features and actuals', '',
              '| function | state | ' + ' | '.join(FEATURES) +
              ' | leaves auto/manual/open | ledger items | minutes | $ |',
              '|---|---|' + '---:|' * len(FEATURES) + '---|---:|---:|---:|']
    for f in m.get('functions', []):
        lg = (f.get('ledger') or {}).get('all') or {}
        lv = f.get('leaves') or {}
        if not lg.get('items') and not f.get('registered') and not f.get('legacy'):
            continue
        fv = features(f)
        lines.append(f'| {f["id"]} {f.get("name", "")} | {f.get("state", "")} | '
                     + ' | '.join(str(fv[k]) for k in FEATURES)
                     + f' | {lv.get("auto", "-")}/{lv.get("manual", "-")}/{lv.get("open", "-")}'
                     + f' | {lg.get("items", 0)} | {_fmt(lg.get("minutes", 0))} | '
                     + f'{_fmt(lg.get("usd", 0))} |')

    lines += ['', '## Auto-closed share before and after each automation item', '',
              '| when | item | function | before | after |', '|---|---|---|---:|---:|']
    for ts, item, fn, a0, t0, a1, t1 in share_history(rows):
        lines.append(f'| {ts} | {item} | {fn} | {a0}/{t0} ({_pct(a0, t0)}) | '
                     f'{a1}/{t1} ({_pct(a1, t1)}) |')

    summed = [k for k in FEATURES if k != 'leaves_estimate']
    lines += ['', '## Target set: functions and features by state', '',
              'Feature sums per state; `leaves_estimate` is the median (path counts grow '
              'exponentially, so a sum says nothing).', '',
              '| state | functions | ' + ' | '.join(summed) + ' | median leaves_estimate |',
              '|---|---:|' + '---:|' * (len(summed) + 1)]
    by_state = {}
    for f in m.get('functions', []):
        if f.get('set') != 'target':
            continue
        by_state.setdefault(f.get('state', '?'), []).append(features(f))
    for st, fvs in sorted(by_state.items()):
        sums = [sum(fv[k] for fv in fvs) for k in summed]
        med = statistics.median(fv['leaves_estimate'] for fv in fvs)
        lines.append(f'| {st} | {len(fvs)} | ' + ' | '.join(str(x) for x in sums)
                     + f' | {_fmt(med)} |')
    return '\n'.join(lines) + '\n'
