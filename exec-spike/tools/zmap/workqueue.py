"""Work queue from map.json, and the function card of `zmap show`."""
from collections import defaultdict

from .merge import CLOSED


def blocker_keys(f):
    for b in f['blockers']:
        if b['kind'] == 'unsupported-form':
            for mn in b['detail']:
                yield f'unsupported-form:{mn}'
        else:
            yield b['kind']


def build_queue(m):
    fns = m['functions']
    by_order = sorted(fns, key=lambda f: (f['order'] is None, f['order'] or 0, f['entry']))
    items = []
    for f in by_order:
        if f['state'] != 'conditional':
            continue
        for c in f['vc_cuts']:
            for leaf in c['leaves']:
                if leaf.get('state') == 'open':
                    items.append({'type': 'leaf', 'fn': f['id'], 'name': f['name'],
                                  'status_id': f['status_id'], 'cut': c['pc'], 'i': leaf.get('i'),
                                  'exit': leaf.get('exit'), 'target': leaf.get('target'),
                                  'residual': leaf.get('residual')})
    for f in by_order:
        for c in f['vc_cuts']:
            if c.get('cut_lemma', 'open') == 'open':
                items.append({'type': 'cut_lemma', 'fn': f['id'], 'name': f['name'],
                              'status_id': f['status_id'], 'cut': c['pc']})
    for f in by_order:
        if f['state'] == 'ready':
            items.append({'type': 'function', 'fn': f['id'], 'name': f['name'],
                          'n_instr': f['n_instr'], 'order': f['order'],
                          'cuts_needing_assertions': len(f['cuts']),
                          'loops_needing_measure': len(f['loops']),
                          'contract_missing': not f.get('contract'),
                          'leaves_estimate': f['leaves_estimate']})
    blocked = defaultdict(list)
    for f in fns:
        if f['set'] == 'target':
            for k in set(blocker_keys(f)):
                blocked[k].append(f)
    for k, fs in sorted(blocked.items(), key=lambda kv: (-sum(f['n_instr'] for f in kv[1]), kv[0])):
        items.append({'type': 'blocker', 'key': k, 'target_instr': sum(f['n_instr'] for f in fs),
                      'functions': sorted(f['id'] for f in fs)})
    for rank, it in enumerate(items, 1):
        it['rank'] = rank
    return items


def describe(it):
    t = it['type']
    if t == 'leaf':
        return (f'leaf {it["status_id"] or it["fn"]} cut {it["cut"]:#x} #{it["i"]} '
                f'exit {it["exit"]} residual {it["residual"]}')
    if t == 'cut_lemma':
        return f'cut lemma {it["status_id"] or it["fn"]} at {it["cut"]:#x}'
    if t == 'function':
        return (f'function {it["fn"]} {it["name"]} ({it["n_instr"]} instr): '
                f'{it["cuts_needing_assertions"]} cuts, {it["loops_needing_measure"]} loops, '
                f'contract {"missing" if it["contract_missing"] else "present"}')
    return f'blocker {it["key"]}: {len(it["functions"])} functions, {it["target_instr"]} target instr'


def queue_markdown(items):
    out = ['# Work queue', '', 'Generated by `python3 -m zmap queue`; order: open leaves of '
           'conditional functions, open cut lemmas, ready functions bottom-up, blockers by '
           'target-set instructions.', '']
    sections = [('leaf', 'Open leaves', ['rank', 'fn', 'cut', 'i', 'exit', 'residual']),
                ('cut_lemma', 'Open cut lemmas', ['rank', 'fn', 'cut']),
                ('function', 'Ready functions', ['rank', 'fn', 'name', 'n_instr', 'cuts_needing_assertions',
                                                 'loops_needing_measure', 'contract_missing']),
                ('blocker', 'Blockers', ['rank', 'key', 'target_instr', 'functions'])]
    for t, title, cols in sections:
        rows = [it for it in items if it['type'] == t]
        out += [f'## {title} ({len(rows)})', '']
        if not rows:
            out += ['None.', '']
            continue
        out.append('| ' + ' | '.join(cols) + ' |')
        out.append('|' + '---|' * len(cols))
        for it in rows:
            cells = []
            for c in cols:
                v = it.get(c)
                if c == 'cut' and isinstance(v, int):
                    v = f'{v:#x}'
                if c == 'functions':
                    v = f'{len(v)}: ' + ', '.join(v[:6]) + (' …' if len(v) > 6 else '')
                cells.append(str(v).replace('|', '\\|'))
            out.append('| ' + ' | '.join(cells) + ' |')
        out.append('')
    return '\n'.join(out)


def find(m, key):
    fns = m['functions']
    for f in fns:
        if key in (f['id'], f['name'], f.get('status_id')) or key in f['aliases']:
            return f
    try:
        pc = int(key, 16)
    except ValueError:
        pc = None
    for f in fns:
        if pc is not None and f['entry'] <= pc < f['entry'] + f['size']:
            return f
    hits = [f for f in fns if key in f['name']]
    if len(hits) == 1:
        return hits[0]
    raise KeyError(key if not hits else f'{key}: ambiguous ({len(hits)} matches)')


def next_action(f, by_id):
    s = f['state']
    if s in CLOSED:
        return 'none'
    if s == 'conditional':
        return f'close {f["open_items"]} open items (zmap next)'
    if s == 'in-proof':
        return 'run zesu_auto and zesu_assemble'
    if s == 'contract-draft':
        return 'review the draft contract'
    if s == 'assumed':
        return 'none (trusted: assumed or service)'
    if s == 'blocked':
        return 'resolve blockers: ' + ', '.join(sorted(set(blocker_keys(f))))
    if s == 'ready':
        return 'write the contract, cut assertions and runs (S6 recipe)'
    if s == 'waiting':
        return 'close callees first: ' + ', '.join(
            f'{c} {by_id[c]["name"]} [{by_id[c]["state"]}]' for c in f.get('waiting_on', []))
    return 'none (not in target)'


def card(m, f):
    by_id = {g['id']: g for g in m['functions']}
    L = [f'{f["id"]}  {f["name"]}' + (f'  ({f["status_id"]})' if f['status_id'] else ''),
         f'  state: {f["state"]}{"  legacy" if f["legacy"] else ""}   set: {f["set"]}   '
         f'entry {f["entry"]:#x}  size {f["size"]}  instr {f["n_instr"]}  order {f["order"]}',
         f'  theorems: ' + ', '.join(f'{k}={"yes" if v else "no"}' for k, v in f['theorems'].items())]
    if f['theorem_names']:
        L.append('  names: ' + ', '.join(f'{k}={v}' for k, v in f['theorem_names'].items() if v))
    c = f.get('contract')
    L.append(f'  contract: {c["contract"]}/{c["review"]} ({c["source"]})' if c else '  contract: none')
    if f['aliases']:
        L.append('  aliases: ' + ', '.join(f['aliases']))
    L.append(f'  blockers: {len(f["blockers"])}')
    for b in f['blockers']:
        d = b['detail']
        if isinstance(d, list):
            d = ' '.join(hex(x) if isinstance(x, int) else str(x) for x in d[:12]) + (' …' if len(d) > 12 else '')
        L.append(f'    {b["kind"]}: {d}')
    L.append(f'  cuts: {len(f["cuts"])}  ' + ' '.join(f'{c["pc"]:#x}:{c["why"]}' for c in f['cuts']))
    L.append(f'  loops: {len(f["loops"])}  ' + ' '.join(f'{l["head"]:#x}({len(l["body"])} blocks)' for l in f['loops']))
    joins = sorted(f['joins'], key=lambda j: -j['fanin_paths'])
    L.append(f'  joins: {len(joins)}  ' + ' '.join(f'{j["at"]:#x}:{j["fanin_paths"]}' for j in joins[:12])
             + (' …' if len(joins) > 12 else ''))
    L.append(f'  join cut candidates: ' + ' '.join(hex(p) for p in f['join_cut_candidates']))
    L.append(f'  leaves_estimate: {f["leaves_estimate"]}')
    L.append(f'  calls: {len(f["calls"])}')
    for cl in f['calls']:
        tg = ', '.join(f'{t} {by_id[t]["name"]} [{by_id[t]["state"]}]' for t in cl['targets'][:4])
        more = f' (+{len(cl["targets"]) - 4})' if len(cl['targets']) > 4 else ''
        nr = ' noreturn' if cl.get('noreturn') else ''
        L.append(f'    {cl["site"]:#x} {cl["kind"]}/{cl["resolution"]}{nr}: {tg or "-"}{more}')
    L.append('  leaves by state: ' + ', '.join(f'{k} {v}' for k, v in f['leaves'].items())
             + '; cut lemmas: ' + ', '.join(f'{k} {v}' for k, v in f['cut_lemmas'].items()))
    lt = f['ledger']['all']
    L.append(f'  ledger: {lt["items"]} items, {lt["minutes"]} min, ${lt["usd"]}, {lt["requests"]} requests')
    L.append(f'  next: {next_action(f, by_id)}')
    return '\n'.join(L)
