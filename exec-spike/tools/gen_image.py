#!/usr/bin/env python3
"""Render `ZesuExec/Image/Gen.lean` (the program image), `ZesuExec/Image/Cfg.lean` (block
starts, loop heads, call sites) and `ZesuExec/Image/Expected.lean` (the mnemonic
`llvm-objdump -M no-aliases` prints at each address) from the pinned Zesu ELF.

Usage:
  gen_image.py --elf E --sha256 H --cfg cfg.json --functions SYM... --rodata ADDR:LEN... --out ZesuExec/Image/Gen.lean
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile

TEXT_LO = 0x80000000
RODATA_LO = 0x8010FD80


def sh(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def section_bytes(elf, name):
    with tempfile.NamedTemporaryFile() as t:
        subprocess.run(["llvm-objcopy", "-O", "binary", f"--only-section={name}", elf, t.name], check=True)
        return open(t.name, "rb").read()


def symbols(elf):
    out = {}
    for line in sh("llvm-readelf", "-s", "--wide", elf).splitlines():
        p = line.split()
        if len(p) >= 8 and p[3] == "FUNC":
            out.setdefault(p[7], (int(p[1], 16), int(p[2])))
    return out


SHORT = {
    "alt_fl_alloc.remap": "F0",
    "array_list.Aligned([32]u8,null).ensureTotalCapacity": "F1",
    "rlp.decodeItem": "F2",
    "rlp_decode.nextUint64": "F3",
    "array_list.Aligned([32]u8,null).toOwnedSlice": "F4",
    "array_list.Aligned(input.AccessListEntry,null).toOwnedSlice": "F5",
    "rlp_decode.decodeParentHeader": "F6",
    "rlp_decode.txAccessList": "TX",
    "rlp_decode.decodeTxFields": "DTF",
    "alt_fl_alloc.alloc": "alloc",
    "alt_fl_alloc.free": "free",
    "memcpy": "memcpy",
}


def lean_ident(sym):
    return SHORT.get(sym) or "fn_" + re.sub(r"[^A-Za-z0-9]", "_", sym)


def chunked(xs, fmt, n=256):
    chunks = [xs[i:i + n] for i in range(0, len(xs), n)] or [[]]
    return " ++\n    ".join("[" + ", ".join(fmt(x) for x in c) + "]" for c in chunks)


def objdump_mnemonics(elf, lo, hi):
    out = {}
    for line in sh("llvm-objdump", "-d", "-M", "no-aliases", f"--start-address={lo:#x}",
                   f"--stop-address={hi:#x}", elf).splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s+([0-9a-f]{8})\s+(\S+)", line)
        if m:
            out[int(m.group(1), 16)] = (int(m.group(2), 16), m.group(3))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", required=True)
    ap.add_argument("--sha256", required=True)
    ap.add_argument("--cfg", required=True)
    ap.add_argument("--functions", nargs="+", required=True)
    ap.add_argument("--rodata", nargs="*", default=[])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    digest = hashlib.sha256(open(a.elf, "rb").read()).hexdigest()
    if digest != a.sha256:
        sys.exit(f"sha256 mismatch: {digest}")
    text = section_bytes(a.elf, ".text")
    rodata = section_bytes(a.elf, ".rodata")
    syms = symbols(a.elf)
    cfg = {f["name"]: f for f in json.load(open(a.cfg))["functions"]}

    segs, expected, cfgdefs = [], [], []
    for sym in a.functions:
        if sym not in syms:
            sys.exit(f"no symbol {sym}")
        base, size = syms[sym]
        if base % 4 or size % 4:
            sys.exit(f"{sym}: not 4-aligned")
        off = base - TEXT_LO
        words = [int.from_bytes(text[off + i:off + i + 4], "little") for i in range(0, size, 4)]
        ident = lean_ident(sym)
        segs.append((sym, ident, base, words))
        mn = objdump_mnemonics(a.elf, base, base + size)
        for i, w in enumerate(words):
            pc = base + 4 * i
            if pc not in mn or mn[pc][0] != w:
                sys.exit(f"{sym}: objdump disagrees at {pc:#x}")
            expected.append((pc, w, mn[pc][1]))
        if sym in cfg:
            f = cfg[sym]
            blocks = sorted(b["start"] for b in f["blocks"])
            heads = sorted({int(e["to"], 16) for l in f["loops"] for e in l["backward_edges"]})
            calls = [(c["pc"], c["target"]) for c in f["calls"]]
            cfgdefs.append((ident, base, blocks, heads, calls, f["returns"]))

    ro = []
    for spec in a.rodata:
        addr, ln = (int(x, 0) for x in spec.split(":"))
        o = addr - RODATA_LO
        if o < 0 or o + ln > len(rodata):
            sys.exit(f"rodata range {spec} outside .rodata")
        ro.append((addr, list(rodata[o:o + ln])))

    hdr = f"-- Generated by tools/gen_image.py from ELF sha256 {digest}. Do not edit.\n"
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as o:
        o.write(hdr + "import ZesuExec.Image\n\nnamespace ZesuExec.Gen\n\n")
        for sym, ident, base, words in segs:
            o.write(f"/-- `{sym}`, {len(words)} instructions. -/\n")
            o.write(f"def {ident} : Seg where\n  base := {base:#x}\n  words :=\n    {chunked(words, hex)}\n\n")
        for i, (addr, bs) in enumerate(ro):
            o.write(f"def rodata_{addr:x} : RoSeg where\n  base := {addr:#x}\n  bytes :=\n    {chunked(bs, str)}\n\n")
        o.write("end ZesuExec.Gen\n\nopen ZesuExec.Gen in\ndef ZesuExec.zesuImage : ZesuExec.Image where\n")
        o.write("  text := [" + ", ".join(s[1] for s in segs) + "]\n")
        o.write("  rodata := [" + ", ".join(f"rodata_{r[0]:x}" for r in ro) + "]\n")

    d = os.path.dirname(a.out)
    with open(os.path.join(d, "Cfg.lean"), "w") as o:
        o.write(hdr + "namespace ZesuExec.Cfg\n\n")
        for ident, base, blocks, heads, calls, rets in cfgdefs:
            o.write(f"def {ident}_entry : Nat := {base:#x}\n")
            o.write(f"def {ident}_blocks : List Nat := [{', '.join(hex(b) for b in blocks)}]\n")
            o.write(f"def {ident}_loopHeads : List Nat := [{', '.join(hex(b) for b in heads)}]\n")
            o.write(f"/-- (call site, target) -/\ndef {ident}_calls : List (Nat × Nat) := ["
                    + ", ".join(f"({p:#x}, {t:#x})" for p, t in calls) + "]\n")
            o.write(f"def {ident}_returns : List Nat := [{', '.join(hex(r) for r in rets)}]\n\n")
        o.write("end ZesuExec.Cfg\n")

    with open(os.path.join(d, "Expected.lean"), "w") as o:
        o.write(hdr + "namespace ZesuExec.Expected\n\n/-- (address, word, `llvm-objdump -M no-aliases` mnemonic) -/\n")
        ch = [expected[i:i + 64] for i in range(0, len(expected), 64)]
        for k, c in enumerate(ch):
            o.write(f"def table_{k} : List (Nat × Nat × String) :=\n    ["
                    + ", ".join(f"({e[0]:#x}, {e[1]:#x}, \"{e[2]}\")" for e in c) + "]\n\n")
        o.write("def table : List (Nat × Nat × String) :=\n  List.flatten ["
                + ", ".join(f"table_{k}" for k in range(len(ch))) + "]\n\nend ZesuExec.Expected\n")


if __name__ == "__main__":
    main()
