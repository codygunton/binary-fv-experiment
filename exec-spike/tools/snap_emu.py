#!/usr/bin/env python3
"""Render emulator snapshots (`tools/svc_test.py --snap-out`, schema `zesu-emusnap/1`) as Lean data
(`ZesuExec.Fn.Emu.ESnap`, `ZesuExec/Fn/EmuSnap.lean`) for the `post_snapshot` theorems of the
functions Unicorn cannot run.

    snap_emu.py --snaps test/snapshots/emu/fn-sha256 --ns ZesuExec.Fn.Sha256 \
        --out ZesuExec/Fn/Sha256/SnapData.lean

Every `mem0` window must have the `mem1` window of the same base and length.
"""
import argparse
import json
from pathlib import Path


def render(path: Path) -> str:
    s = json.loads(path.read_text())
    assert s['schema'] == 'zesu-emusnap/1', path
    after = {w['base']: bytes.fromhex(w['hex']) for w in s['mem1']}
    wins = []
    for w in s['mem0']:
        b0 = bytes.fromhex(w['hex'])
        b1 = after[w['base']]
        assert len(b0) == len(b1), (path, w['base'])
        wins.append(f"({w['base']:#x}, \"{b0.hex()}\", \"{b1.hex()}\")")
    return (f"  -- {s['check']} case {s['case']}\n"
            f"  .ofHex {s['regs0']} {s['regs1']} {s['pc1']:#x}\n"
            f"    [{', '.join(wins)}]")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--snaps', required=True, type=Path)
    ap.add_argument('--ns', required=True)
    ap.add_argument('--out', required=True, type=Path)
    a = ap.parse_args(argv)
    files = sorted(a.snaps.glob('*.json'), key=lambda p: (len(p.stem), p.stem))
    body = ',\n'.join(render(p) for p in files)
    a.out.write_text(
        f"import ZesuExec.Fn.EmuSnap\n\n"
        f"/-! Generated by `tools/snap_emu.py --snaps {a.snaps}`: {len(files)} emulator snapshots. -/\n\n"
        f"namespace {a.ns}\n\n"
        f"def snaps : List ZesuExec.Fn.Emu.ESnap := [\n{body}]\n\n"
        f"end {a.ns}\n")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
