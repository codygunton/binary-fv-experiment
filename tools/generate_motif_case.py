#!/usr/bin/env python3
"""Emit one motif-lemma case file, and count its lines.

Every case in the campaign has the same four parts — baseline chain, lemma, applications, and the
line count — and they differ only in `n` and the site list. Generating them makes the comparison
identical across cases by construction: a hand-written baseline that happened to be terser than a
hand-written lemma would measure my prose, not the motif.

The generated proof is the *composition* only. The per-instruction `Runs (try_step …)` premises stay
as arguments on both sides, because they are per-site semantics that neither a chain nor a lemma
removes; counting them on one side would rig the result.

Usage:
    python3 tools/generate_motif_case.py --case A --n 10 \
        --sites 70,fc,1fcc,2130,2338,238c,2b24 --out BinaryFv/Zesu/Motifs/CaseA.lean
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys


def address(k: int) -> str:
    """`start`, `(start + 4)`, `((start + 4) + 4)`, …

    Nested rather than `start + 4k`: `(start + 4k) + 4` and `start + 4(k+1)` are not definitionally
    equal for `BitVec`, so the flat form needs an associativity rewrite at every step. This form
    needs none. It is a constraint on how a motif lemma may be stated, not a preference.
    """
    return "start" if k == 0 else "(" + address(k - 1) + " + 4)"


def site_address(base: int, k: int) -> str:
    return address(k).replace("start", f"(BitVec.ofNat 64 0x{base:x})")


HEADER = '''import BinaryFv.Zesu.Machine.RegisterWrite
import BinaryFv.Zesu.Machine.Target

/-!
# Case {case} — a motif of {n} instructions at {sites} sites, measured in lines

Sites: {site_list}.

GENERATED by `tools/generate_motif_case.py`. Both sides of the comparison come from one generator,
so neither can be terser than the other by accident.

## What is compared

`baselineChain` is what an author writes for one site with no motif lemma: {n} chained `Seg.step`s.
`motifCase` is the same thing stated once. `site_*` are the {sites} applications.

The per-instruction `Runs (try_step …)` premises are arguments on both sides. They are per-site
semantics and neither form removes them, so counting them on one side only would rig the result.
What a motif lemma removes is the **composition** — which `PLAN_PROOF_PATTERNS.md` identified as the
remaining bulk the step-layer toolkit does not reach.

## Side conditions found by writing this

- **`adv`** — `Sail.BitVec.addInt q 4 = q + 4`. The concrete baseline gets this by `decide` because
  its addresses are literals; a lemma over a symbolic `start` cannot, so it becomes a hypothesis.
  One per site, not one per instruction.
- **Address association** — see `address` in the generator. The flat `start + 4k` form needs a
  rewrite at every step; the nested form needs none.

Neither appears in the n-gram study's `uses × (n−1)`.
-/

namespace BinaryFv.Zesu.Motifs.Case{case}

open BinaryFv BinaryFv.Binary BinaryFv.Binary.Elfling BinaryFv.RiscV
open BinaryFv.Zesu.Machine BinaryFv.Zesu.Generated
open PreSail LeanRV64DExecutable.Functions Register

/-- Everything one register-writing step needs that is not the incoming segment. -/
structure StepData (W : RegSet) (pc : BitVec 64) (stepNo : Nat) where
  dest : Register
  value : RegisterType dest
  run : ∀ cur : State, ∃ r, Runs (try_step stepNo false) cur
    (afterRegisterWrite cur pc r dest value) false
  destination : W dest
  destNotPc : dest ≠ PC
  destNotRetired : dest ≠ minstret

/-- The same, for a store: it writes memory rather than a register, so `Seg.stepStore` consumes it
and the segment learns nothing about registers. -/
structure StoreData (M : Region) (pc : BitVec 64) (stepNo : Nat) where
  width : Nat
  address : Nat
  value : BitVec (8 * width)
  run : ∀ cur : State, ∃ r, Runs (try_step stepNo false) cur
    (tryStepControlFlowAfterRetired
      (afterWriteBytes (coreControlFlowNextState (tryStepControlFlowAfterIncrement cur) pc)
        address value) (Sail.BitVec.addInt pc 4) r) false
  inside : ∀ other, address ≤ other → other < address + width → M other
'''


def emit(case: str, n: int, sites: list[int], kinds: list[str]) -> str:
    first = sites[0]
    parts = [HEADER.format(case=case, n=n, sites=len(sites),
                           site_list=", ".join(f"`0x{a:x}`" for a in sites))]

    # --- baseline: one concrete site, n chained steps
    def decl(k, addr, ind="    "):
        return (f"{ind}(s{k} : StepData W {addr} {k})" if kinds[k] == "reg"
                else f"{ind}(s{k} : StoreData M {addr} {k})")
    decls = "\n".join(decl(k, f"(BitVec.ofNat 64 0x{first + 4 * k:x})") for k in range(n))
    def step(k, nxt, adv):
        prev = "seg" if k == 0 else f"g{k - 1}"
        if kinds[k] == "reg":
            return (f"  obtain ⟨n{k}, g{k}⟩ := {prev}.step (inRegion _) (notExit _)\n"
                    f"    s{k}.dest s{k}.value {nxt} (s{k}.run _) {adv}\n"
                    f"    bookkeeping s{k}.destination s{k}.destNotPc s{k}.destNotRetired"
                    f" (keep _ _)")
        return (f"  obtain ⟨n{k}, g{k}⟩ := {prev}.stepStore s{k}.address s{k}.value {nxt}\n"
                f"    (inRegion _) (notExit _) (s{k}.run _) {adv} s{k}.inside bookkeeping"
                f" (keepStore _)")
    steps = "\n".join(
        step(k, f"(BitVec.ofNat 64 0x{first + 4 * (k + 1):x})", "(by decide)") for k in range(n))
    parts.append(f'''
/-! ## Baseline — one site, no lemma -/

theorem baselineChain {{own exit : BitVec 64 → Prop}}
    {{childSummary : FunctionInstanceId → Nat → Nat → State → State → Prop}}
    {{W : RegSet}} {{M : Region}} {{base cur : State}} {{kv : List RegVal}}
    (seg : Seg own exit childSummary W M kv 0 0 base cur (BitVec.ofNat 64 0x{first:x}))
{decls}
    (inRegion : ∀ p, own p) (notExit : ∀ p, ¬ exit p)
    (bookkeeping : ∀ r, stepBookkeeping r → W r)
    (keep : ∀ (d : Register) (l : List RegVal),
      RegsOutside (RegSet.union stepBookkeeping (RegSet.only d)) l)
    (keepStore : ∀ l : List RegVal, RegsOutside stepBookkeeping l) :
    ∃ next kv', Seg own exit childSummary W M kv' 0 {n} base next
      (BitVec.ofNat 64 0x{first + 4 * n:x}) := by
{steps}
  exact ⟨n{n - 1}, _, g{n - 1}⟩
''')

    # --- the lemma
    lemma_decls = "\n".join(
        (f"  s{k} : StepData W {address(k)} {k}" if kinds[k] == "reg"
         else f"  s{k} : StoreData M {address(k)} {k}") for k in range(n))
    lemma_steps = "\n".join(step(k, address(k + 1), "(adv _)") for k in range(n))
    parts.append(f'''
/-! ## The lemma -/

/-- The {n} per-instruction bundles of one site, as one argument. -/
structure MotifData (W : RegSet) (M : Region) (start : BitVec 64) where
{lemma_decls}

theorem motifCase {{own exit : BitVec 64 → Prop}}
    {{childSummary : FunctionInstanceId → Nat → Nat → State → State → Prop}}
    {{W : RegSet}} {{M : Region}} {{base cur : State}} {{kv : List RegVal}} {{start : BitVec 64}}
    (seg : Seg own exit childSummary W M kv 0 0 base cur start)
    (d : MotifData W M start)
    (inRegion : ∀ p, own p) (notExit : ∀ p, ¬ exit p)
    (bookkeeping : ∀ r, stepBookkeeping r → W r)
    (adv : ∀ q : BitVec 64, Sail.BitVec.addInt q 4 = q + 4)
    (keep : ∀ (r : Register) (l : List RegVal),
      RegsOutside (RegSet.union stepBookkeeping (RegSet.only r)) l)
    (keepStore : ∀ l : List RegVal, RegsOutside stepBookkeeping l) :
    ∃ next kv', Seg own exit childSummary W M kv' 0 {n} base next {address(n)} := by
  obtain ⟨{", ".join(f"s{k}" for k in range(n))}⟩ := d
{lemma_steps}
  exact ⟨n{n - 1}, _, g{n - 1}⟩
''')

    # --- applications
    apps = "\n\n".join(f'''theorem site_{a:x} {{own exit : BitVec 64 → Prop}}
    {{childSummary : FunctionInstanceId → Nat → Nat → State → State → Prop}}
    {{W : RegSet}} {{M : Region}} {{base cur : State}} {{kv : List RegVal}}
    (seg : Seg own exit childSummary W M kv 0 0 base cur (BitVec.ofNat 64 0x{a:x}))
    (d : MotifData W M (BitVec.ofNat 64 0x{a:x}))
    (inRegion : ∀ p, own p) (notExit : ∀ p, ¬ exit p)
    (bookkeeping : ∀ r, stepBookkeeping r → W r)
    (adv : ∀ q : BitVec 64, Sail.BitVec.addInt q 4 = q + 4)
    (keep : ∀ (r : Register) (l : List RegVal),
      RegsOutside (RegSet.union stepBookkeeping (RegSet.only r)) l)
    (keepStore : ∀ l : List RegVal, RegsOutside stepBookkeeping l) :
    ∃ next kv', Seg own exit childSummary W M kv' 0 {n} base next {site_address(a, n)} :=
  motifCase seg d inRegion notExit bookkeeping adv keep keepStore''' for a in sites)
    parts.append(f'''
/-! ## The {len(sites)} sites, one application each -/

{apps}

end BinaryFv.Zesu.Motifs.Case{case}
''')
    return "".join(parts)


def count(text: str) -> dict:
    """Code lines per part. Comments and blanks excluded, same rule everywhere."""
    lines = text.split("\n")

    def code(block: list[str]) -> int:
        return sum(1 for l in block
                   if l.strip() and not re.match(r"^\s*(--|/-|\*|-/)", l.strip()))

    def block(prefix: str) -> list[str]:
        start = next((i for i, l in enumerate(lines) if l.startswith(prefix)), None)
        if start is None:
            return []
        out = [lines[start]]
        for l in lines[start + 1:]:
            if l.startswith(("theorem ", "structure ", "/-!", "end ")):
                break
            out.append(l)
        return out

    first_site = next((l for l in lines if l.startswith("theorem site_")), "")
    return {
        "baseline": code(block("theorem baselineChain")),
        "lemma": code(block("theorem motifCase")) + code(block("structure MotifData")),
        "application": code(block(first_site.split(" ")[0] + " " + first_site.split(" ")[1])
                            if first_site else []),
        "stepData": code(block("structure StepData")),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", required=True)
    parser.add_argument("--n", type=int, required=True)
    parser.add_argument("--sites", required=True, help="comma-separated hex, no 0x")
    parser.add_argument("--kinds", default=None,
                        help="comma-separated reg|store per instruction; default all reg")
    parser.add_argument("--out", type=pathlib.Path, required=True)
    arguments = parser.parse_args()

    sites = [int(x, 16) for x in arguments.sites.split(",")]
    kinds = (arguments.kinds.split(",") if arguments.kinds
             else ["reg"] * arguments.n)
    if len(kinds) != arguments.n:
        raise SystemExit(f"--kinds has {len(kinds)} entries, need {arguments.n}")
    text = emit(arguments.case, arguments.n, sites, kinds)
    arguments.out.parent.mkdir(parents=True, exist_ok=True)
    arguments.out.write_text(text)

    counts = count(text)
    s, n = len(sites), arguments.n
    no_lemma = s * counts["baseline"]
    with_lemma = counts["lemma"] + s * counts["application"]
    counts.update({
        "case": arguments.case, "n": n, "sites": s,
        "totalNoLemma": no_lemma, "totalWithLemma": with_lemma,
        "linesSaved": no_lemma - with_lemma,
        "savedFraction": (no_lemma - with_lemma) / no_lemma if no_lemma else 0.0,
        "breakEvenSites": (counts["lemma"] / (counts["baseline"] - counts["application"])
                           if counts["baseline"] > counts["application"] else None),
    })
    json.dump(counts, sys.stdout, indent=1, sort_keys=True)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
