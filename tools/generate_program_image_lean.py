#!/usr/bin/env python3
"""Generate a Lean ProgramImage constant from one pinned ELF."""

from __future__ import annotations

import argparse
from pathlib import Path

from elftools.elf.elffile import ELFFile
from elf_identity import load_image_sha256


def byte_array(name: str, data: bytes) -> list[str]:
    lines: list[str] = []
    chunk_names: list[str] = []
    for chunk_index, start in enumerate(range(0, len(data), 512)):
        chunk_name = f"{name}Chunk{chunk_index}"
        chunk_names.append(chunk_name)
        chunk = data[start : start + 512]
        lines.append(f"private def {chunk_name} : ByteArray := ByteArray.mk #[")
        for row in range(0, len(chunk), 12):
            values = ", ".join(f"0x{byte:02x}" for byte in chunk[row : row + 12])
            lines.append(f"  {values},")
        lines.extend([
            "]",
            "",
        ])
    expression = " ++ ".join(chunk_names) if chunk_names else "ByteArray.empty"
    lines.append(f"private def {name} : ByteArray := {expression}")
    return lines


def generate(elf_path: Path, expected_sha256: str) -> str:
    actual_sha256 = load_image_sha256(elf_path)
    if actual_sha256 != expected_sha256:
        raise ValueError(
            f"ELF load-image digest mismatch: expected {expected_sha256}, observed {actual_sha256}"
        )
    with elf_path.open("rb") as stream:
        elf = ELFFile(stream)
        segments = [segment for segment in elf.iter_segments() if segment["p_type"] == "PT_LOAD"]
        if not segments:
            raise ValueError("ELF has no loadable segments")
        lines = [
            "/- Generated by tools/generate_program_image_lean.py from the production ELF. -/",
            "import BinaryFv.Binary.ProgramImage",
            "",
            "namespace BinaryFv.Zesu.Artifacts.Program",
            "",
            "open BinaryFv.Binary",
            "",
            'def artifactIdentityScope : String := "ELF PT_LOAD memory image"',
            f'def artifactSha256 : String := "{actual_sha256}"',
            "",
        ]
        for index, segment in enumerate(segments):
            data = segment.data()
            if len(data) != segment["p_filesz"]:
                raise ValueError(f"load segment {index} data length disagrees with p_filesz")
            lines.extend(byte_array(f"segment{index}Bytes", data))
            lines.append("")
        lines.extend([
            "def image : ProgramImage := {",
            "  segments := #[",
        ])
        for index, segment in enumerate(segments):
            lines.extend([
                "    {",
                f"      virtualAddress := {int(segment['p_vaddr']):#x}",
                f"      initialBytes := segment{index}Bytes",
                f"      memorySize := {int(segment['p_memsz']):#x}",
                f"      flags := {int(segment['p_flags'])}",
                "    },",
            ])
        lines.extend([
            "  ]",
            "}",
            "",
            "end BinaryFv.Zesu.Artifacts.Program",
            "",
        ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--elf", required=True, type=Path)
    parser.add_argument("--expected-sha256", required=True)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.elf, args.expected_sha256))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
