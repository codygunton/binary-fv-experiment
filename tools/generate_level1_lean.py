#!/usr/bin/env python3
"""Emit stable Lean identifiers for the exact generated Level 1 instances."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


NAMES = {
    "read_input": "readInput",
    "zkvm_exit": "zkvmExit",
    "alt_fl_alloc.get": "allocatorGet",
    "ssz_decode_root.decodeInput": "decodeInput",
    "ssz_decode_observation.writeSuccess": "writeSuccess",
    "ssz_decode_observation.writeFailure": "writeFailure",
}


def pc_ranges(values: list[int]) -> list[tuple[int, int]]:
    """Compress sorted RV64 instruction PCs into exact half-open four-byte ranges."""
    if values != sorted(set(values)):
        raise ValueError("instruction PCs must be sorted and unique")
    ranges: list[tuple[int, int]] = []
    for pc in values:
        if pc % 4:
            raise ValueError(f"instruction PC is not four-byte aligned: {pc:#x}")
        if ranges and pc == ranges[-1][1]:
            ranges[-1] = (ranges[-1][0], pc + 4)
        else:
            ranges.append((pc, pc + 4))
    expanded = [pc for start, stop in ranges for pc in range(start, stop, 4)]
    if expanded != values:
        raise AssertionError("PC range compression changed the instruction set")
    return ranges


def lean_ranges(values: list[int]) -> str:
    ranges = pc_ranges(values)
    if not ranges:
        return "[]"
    rows = [f"  ({start:#x}, {stop:#x})" for start, stop in ranges]
    return "[\n" + ",\n".join(rows) + "\n]"


def lean_nats(values: list[int]) -> str:
    return "[" + ", ".join(hex(value) for value in values) + "]"


def syscall_pcs(cfg: dict, manifest: dict) -> dict[str, int]:
    functions = {row["name"]: row for row in cfg["functions"]}
    result: dict[str, int] = {}
    for qualified in ("read_input", "write_output", "zkvm_exit"):
        function = functions[qualified]
        ecalls = [
            instruction
            for block in function["blocks"]
            for instruction in block["instructions"]
            if instruction["mnemonic"] == "ecall"
        ]
        if len(ecalls) != 1 or ecalls[0]["bytes"] != "73000000":
            raise ValueError(f"{qualified} must contain exactly one canonical ecall")
        result[qualified] = ecalls[0]["pc"]
    return result


def generate(manifest: dict, cfg: dict) -> str:
    rows = {row["qualified"]: row for row in manifest["instances"]}
    if set(rows) != set(NAMES):
        raise ValueError("Level 1 Lean generation requires the reviewed six-instance inventory")
    lines = [
        "/- This file is generated by tools/generate_level1_lean.py. -/",
        "namespace BinaryFv.Ssz.Generated",
        "",
        "/-- A half-open, four-byte-aligned interval of production instruction addresses. -/",
        "abbrev PcRange := Nat × Nat",
        "",
        f'def artifactSha256 : String := "{manifest["artifact"]["sha256"]}"',
        "",
    ]
    if cfg["artifact"]["sha256"] != manifest["artifact"]["sha256"]:
        raise ValueError("CFG and Level 1 manifest describe different ELFs")
    mains = [row for row in cfg["functionInstances"]
             if row["kind"] == "concrete" and row["parent"] is None
             and row["name"] == "ssz_decode_root.main"]
    if len(mains) != 1:
        raise ValueError("expected one concrete SSZ endpoint main instance")
    selected_extent = {pc for row in manifest["instances"] for pc in row["executionPcs"]}
    glue_pcs = sorted(set(mains[0]["pcs"]) - selected_extent)
    if len(glue_pcs) != 24:
        raise ValueError("expected exactly 24 Level 0 parent-owned instructions")
    lines.extend([
        f"def mainEntry : Nat := {mains[0]['entryPc']:#x}",
        f"def mainGlueInstructionCount : Nat := {len(glue_pcs)}",
        f"def mainGluePcRanges : List PcRange := {lean_ranges(glue_pcs)}",
        "",
    ])
    for qualified, lean_name in NAMES.items():
        row = rows[qualified]
        lines.extend([
            f"def {lean_name}Entry : Nat := {hex(row['entryPc'])}",
            f"def {lean_name}OwnedInstructionCount : Nat := {len(row['instructionPcs'])}",
            f"def {lean_name}AbsorbedInstructionCount : Nat := {len(row['absorbedInstructionPcs'])}",
            f"def {lean_name}ExecutionInstructionCount : Nat := {len(row['executionPcs'])}",
            f"def {lean_name}OwnedPcRanges : List PcRange := {lean_ranges(row['instructionPcs'])}",
            f"def {lean_name}ExecutionPcRanges : List PcRange := {lean_ranges(row['executionPcs'])}",
            f"def {lean_name}ExitPcs : List Nat := {lean_nats(row['exitPcs'])}",
            "",
        ])
    decode_exits = rows["ssz_decode_root.decodeInput"]["exitPcs"]
    if len(decode_exits) != 1:
        raise ValueError("decodeInput requires one exact return PC")
    zkvm_exits = rows["zkvm_exit"]["exitPcs"]
    if len(zkvm_exits) != 1:
        raise ValueError("zkvm_exit requires one exact terminal PC")
    lines.extend([
        f"def zkvmExitTerminalPc : Nat := {zkvm_exits[0]:#x}",
        "",
    ])
    ecalls = syscall_pcs(cfg, manifest)
    lines.extend([
        f"def readInputEcallPc : Nat := {ecalls['read_input']:#x}",
        f"def writeOutputEcallPc : Nat := {ecalls['write_output']:#x}",
        f"def zkvmExitEcallPc : Nat := {ecalls['zkvm_exit']:#x}",
        "",
    ])
    lines.append("end BinaryFv.Ssz.Generated")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--cfg", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(
        json.loads(args.manifest.read_text()), json.loads(args.cfg.read_text())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
