#!/usr/bin/env python3
"""Emit per-address instruction facts as Lean, from the machine-regions database.

`generate_machine_regions.py` already decodes every instruction in the production ELF and records
its mnemonic, operands, word and register read/write sets in `machine-regions.json`. Only the
`(address, word)` column reaches Lean; the rest is dropped at that boundary. Machine-execution
proofs then re-derive the same fields by hand, once per site.

This emits the dropped columns for the addresses the proof layer actually mentions, so a step proof
looks its instruction up instead of restating it. Scoped deliberately: the proof tree references
about a hundred of the ELF's 3,369 instructions, and a table covering all of them would cost more
to check than the proofs it saves.

The output is evidence, not an axiom, exactly as `tools/README.md` requires. Every row's word is
checked against `Artifacts.programImage` by `instructionFactsMatchImage`, which reads the
file-backed bytes -- the same currency `CodeIntact` preserves -- and is independent of the Sail
decode path `wordsMatch` already checks. A wrong row fails that check rather than silently
weakening a proof.

This should fold into `generate_machine_regions.py` so it runs under the same pinned-LLVM,
built-twice, byte-identical Nix target. It is separate here only so it can be developed without a
Nix rebuild in the loop.

Usage: generate_instruction_facts.py <machine-regions.json> <addresses-file> <out.lean>
where <addresses-file> holds one hex or decimal address per line.
"""
import json, sys, re

# RISC-V mnemonic -> the instruction-class lemma family a proof would use. Pseudo-instructions are
# mapped to the real encoding the Sail model decodes them as, because that is what `ext_decode`
# produces and therefore what a class lemma must match.
CLASS = {
    'addi': 'ITYPE', 'li': 'ITYPE', 'mv': 'ITYPE', 'andi': 'ITYPE', 'ori': 'ITYPE',
    'xori': 'ITYPE', 'slti': 'ITYPE', 'sltiu': 'ITYPE',
    'slli': 'SHIFTIOP', 'srli': 'SHIFTIOP', 'srai': 'SHIFTIOP',
    'add': 'RTYPE', 'sub': 'RTYPE', 'and': 'RTYPE', 'or': 'RTYPE', 'xor': 'RTYPE',
    'sltu': 'RTYPE', 'slt': 'RTYPE',
    'auipc': 'UTYPE_AUIPC', 'lui': 'UTYPE_LUI',
    'lb': 'LOAD', 'lbu': 'LOAD', 'lh': 'LOAD', 'lhu': 'LOAD',
    'lw': 'LOAD', 'lwu': 'LOAD', 'ld': 'LOAD',
    'sb': 'STORE', 'sh': 'STORE', 'sw': 'STORE', 'sd': 'STORE',
    'beq': 'BTYPE', 'bne': 'BTYPE', 'blt': 'BTYPE', 'bge': 'BTYPE',
    'bltu': 'BTYPE', 'bgeu': 'BTYPE', 'beqz': 'BTYPE', 'bnez': 'BTYPE',
    'j': 'JAL', 'jal': 'JAL', 'jalr': 'JALR', 'ret': 'JALR_RET',
}

def load_addresses(path):
    out = []
    for line in open(path):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        out.append(int(line, 16) if line.startswith('0x') else int(line))
    return sorted(set(out))

def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    regions, addrfile, out = sys.argv[1], sys.argv[2], sys.argv[3]
    ins = {r['address']: r for r in json.load(open(regions))['instructions']}
    addrs = [a for a in load_addresses(addrfile) if a in ins]
    missing = [a for a in load_addresses(addrfile) if a not in ins]

    rows = []
    unclassified = []
    for a in addrs:
        r = ins[a]
        cls = CLASS.get(r['mnemonic'])
        if cls is None:
            unclassified.append((a, r['mnemonic']))
            continue
        rows.append((a, r['word'], cls, r['mnemonic'], r['operands'], r['writes']))

    L = []
    L.append('import BinaryFv.Zesu.ControlFlow.MachineRegions')
    L.append('')
    L.append('/-!')
    L.append('# Per-address instruction facts, generated')
    L.append('')
    L.append('Generated by `tools/generate_instruction_facts.py` from the machine-regions database,')
    L.append('which decodes the production ELF under pinned LLVM. Do not edit by hand.')
    L.append('')
    L.append('`generate_machine_regions.py` computes each instruction\'s mnemonic, operands and')
    L.append('register write set and drops all of them at the Lean boundary, emitting only')
    L.append('`(address, word)`. Machine-execution proofs then restate those fields by hand once per')
    L.append('site. This table carries them across, scoped to the addresses the proof layer names.')
    L.append('')
    L.append('The table is evidence, not an axiom. `instructionFactsMatchImage` checks every row\'s')
    L.append('word against the file-backed bytes of `Artifacts.programImage` -- the currency')
    L.append('`CodeIntact` preserves -- independently of the Sail-decode check `wordsMatch` already')
    L.append('applies to the same rows. A wrong row fails that check.')
    L.append('-/')
    L.append('')
    L.append('namespace BinaryFv.Zesu.MachineRegions')
    L.append('')
    L.append('/-- `(address, word)` for every instruction the proof layer names. -/')
    L.append('def provenInstructionWords : Array (Nat × Nat) := #[')
    for a, w, *_ in rows:
        L.append(f'  ({a}, {w}),')
    if rows:
        L[-1] = L[-1].rstrip(',')
    L.append(']')
    L.append('')
    L.append('/-- Every listed word is the little-endian file image at its address. Checked against')
    L.append('the pinned ELF, not assumed. -/')
    L.append('def instructionFactsMatchImage (image : BinaryFv.Binary.ProgramImage) : Bool :=')
    L.append('  provenInstructionWords.all fun entry =>')
    L.append('    image.readFileU32LE? entry.1 == some entry.2')
    L.append('')
    L.append('theorem provenInstructionWords_match_image :')
    L.append('    instructionFactsMatchImage BinaryFv.Zesu.Artifacts.programImage = true := by')
    L.append('  native_decide')
    L.append('')
    L.append('end BinaryFv.Zesu.MachineRegions')
    open(out, 'w').write('\n'.join(L) + '\n')

    print(f"emitted {len(rows)} rows to {out}")
    if unclassified:
        print(f"  {len(unclassified)} addresses had an unmapped mnemonic (add to CLASS):")
        for a, m in unclassified[:10]:
            print(f"    0x{a:x}  {m}")
    if missing:
        print(f"  {len(missing)} requested addresses are not instruction starts (skipped)")
    by = {}
    for _, _, c, *_ in rows:
        by[c] = by.get(c, 0) + 1
    print("  by class: " + ', '.join(f"{k}={v}" for k, v in sorted(by.items(), key=lambda kv: -kv[1])))

if __name__ == '__main__':
    main()
