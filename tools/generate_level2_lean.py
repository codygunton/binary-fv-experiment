#!/usr/bin/env python3
"""Emit source-derived Lean identifiers for the reviewed Level 2 instances."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from generate_level1_lean import lean_nats, lean_ranges


UNIQUE_NAMES = {
    "memcpy": "memcpy",
    "ssz.decode": "sszDecode",
    "ssz_decode_observation.Encoder.transactions": "writeSuccessTransactions",
    "ssz_decode_observation.Encoder.withdrawals": "writeSuccessWithdrawals",
    "ssz_decode_observation.Encoder.hashes": "writeSuccessHashes",
    "ssz_decode_observation.Encoder.boolean": "writeSuccessBoolean",
    "ssz_decode_observation.Encoder.optionalU64": "writeSuccessOptionalU64",
    "ssz_decode_observation.Encoder.byteLists": "writeSuccessByteLists",
    "ssz_decode_observation.Encoder.bytes": "writeSuccessBytes",
    "ssz_decode_observation.Encoder.int": "writeSuccessInt",
}


def source_name(row: dict, cfg_instances: dict[str, dict]) -> str:
    qualified = row["qualified"]
    stack = row["functionInstanceIdentity"]["inlineStack"]
    if qualified == "ssz_decode_observation.Encoder.raw":
        caller = cfg_instances[row["parentInstanceIds"][0]]["name"]
        line = stack[-1]["callSite"]["line"]
        prefix = "writeSuccess" if caller.endswith("writeSuccess") else "writeFailure"
        return f"{prefix}RawLine{line}"
    return UNIQUE_NAMES[qualified]


def generate(manifest: dict, cfg: dict) -> str:
    if cfg["artifact"] != manifest["artifact"]:
        raise ValueError("CFG and Level 2 manifest describe different ELFs")
    if len(manifest["instances"]) != 20:
        raise ValueError("expected the reviewed 20-instance bare-metal Level 2 inventory")
    cfg_instances = {row["id"]: row for row in cfg["functionInstances"]}
    names = [source_name(row, cfg_instances) for row in manifest["instances"]]
    if len(names) != len(set(names)):
        raise ValueError("source-derived Level 2 names are not unique")
    lines = [
        "/- This file is generated by tools/generate_level2_lean.py. -/",
        "import BinaryFv.Zesu.Elflings.GeneratedLevel1",
        "",
        "namespace BinaryFv.Zesu.Elflings",
        "",
        f'def level2ArtifactIdentityScope : String := "{manifest["artifact"]["identityScope"]}"',
        f'def level2ArtifactSha256 : String := "{manifest["artifact"]["sha256"]}"',
        f"def level2InstanceCount : Nat := {len(names)}",
        "",
    ]
    for row, name in zip(manifest["instances"], names, strict=True):
        parents = "[" + ", ".join(f'\"{value}\"' for value in row["parentInstanceIds"]) + "]"
        lines.extend([
            f"def {name}InstanceId : String := \"{row['id']}\"",
            f"def {name}Entry : Nat := {row['entryPc']:#x}",
            f"def {name}OwnedInstructionCount : Nat := {row['ownedInstructionCount']}",
            f"def {name}ExecutionInstructionCount : Nat := {len(row['executionPcs'])}",
            f"def {name}OwnedPcRanges : List PcRange := {lean_ranges(row['instructionPcs'])}",
            f"def {name}ExecutionPcRanges : List PcRange := {lean_ranges(row['executionPcs'])}",
            f"def {name}ExitPcs : List Nat := {lean_nats(row['exitPcs'])}",
            f"def {name}ParentInstanceIds : List String := {parents}",
            "",
        ])
    lines.extend(["end BinaryFv.Zesu.Elflings", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--cfg", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(json.loads(args.manifest.read_text()),
                                    json.loads(args.cfg.read_text())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
